#!/usr/bin/env node
/**
 * tools/coverage.js — how many cards actually have working scripts?
 *
 *   node tools/coverage.js            print a summary
 *   node tools/coverage.js --write    also write card_database/CARD_COVERAGE_REPORT.md
 *   node tools/coverage.js --check    exit 1 if a card in the DB / a deck is neither scripted nor honestly listed
 *
 * Two populations are measured:
 *   1. every card in card_database/yugioh_cards.jsonl  ("the database")
 *   2. every card in every deck in deck_inventory/     ("your decks")
 * A card is: vanilla (nothing to script) | scripted | partial (scripted, with
 * a note on what's missing) | stub (plays as a plain card; text not implemented).
 */
"use strict";
const fs = require("fs");
const path = require("path");
const LocalCards = require("../LocalCards");
const CardScripts = require("../CardScripts");
const DeckInventory = require("../DeckInventory");
const Effects = require("../Effects");

CardScripts.loadAll();

function classify(card) { return CardScripts.cardStatus(card); }

function summarize(cards) {
    const out = { total: 0, vanilla: 0, scripted: 0, partial: 0, stub: 0, byName: new Map() };
    for (const c of cards) {
        if (out.byName.has(c.name)) continue;
        const st = classify(c);
        out.byName.set(c.name, st);
        out.total++; out[st.status]++;
    }
    return out;
}
const pct = (n, t) => (t ? ((n / t) * 100).toFixed(1) : "0.0") + "%";

// ---- 1. database ------------------------------------------------------------
const dbCards = LocalCards.all().map(r => LocalCards.toApiShape(r));
const db = summarize(dbCards);
const dbSpellTrap = summarize(dbCards.filter(c => /Spell|Trap/.test(c.type)));
const dbMonsters = summarize(dbCards.filter(c => /Monster/.test(c.type)));

// ---- 2. decks ----------------------------------------------------------------
const deckRows = DeckInventory.list().filter(d => !d.broken).map(d => {
    const deck = DeckInventory.readDeck(d.id);
    const s = summarize([...deck.mainDeck, ...deck.extraDeck]);
    return { id: d.id, name: d.name, s };
});

const lines = [];
const P = s => { lines.push(s); };
P("# Card script coverage");
P("");
P("Generated by `node tools/coverage.js --write`. Do not edit by hand.");
P("");
P("| status | meaning |");
P("|---|---|");
P("| vanilla | Normal Monster, no card text to implement |");
P("| scripted | the card's effect text is implemented and covered by tests |");
P("| partial | implemented, but the note says which clause is missing |");
P("| stub | can be drawn and played as a plain card; its effect text is **not** implemented |");
P("");
P("## Card database (`yugioh_cards.jsonl`)");
P("");
P("| | cards | vanilla | scripted | partial | stub | implemented |");
P("|---|---:|---:|---:|---:|---:|---:|");
for (const [label, s] of [["All cards", db], ["Monsters", dbMonsters], ["Spells & Traps", dbSpellTrap]]) {
    P(`| ${label} | ${s.total} | ${s.vanilla} | ${s.scripted} | ${s.partial} | ${s.stub} | ${pct(s.vanilla + s.scripted + s.partial, s.total)} |`);
}
P("");
P("## Your decks (`deck_inventory/`)");
P("");
P("| deck | unique cards | vanilla | scripted | partial | stub | implemented |");
P("|---|---:|---:|---:|---:|---:|---:|");
for (const d of deckRows) {
    const s = d.s;
    P(`| ${d.name} | ${s.total} | ${s.vanilla} | ${s.scripted} | ${s.partial} | ${s.stub} | ${pct(s.vanilla + s.scripted + s.partial, s.total)} |`);
}
P("");
P("### Partial scripts — what is NOT implemented");
P("");
const partials = new Map();
for (const d of deckRows) for (const [n, st] of d.s.byName) if (st.status === "partial") partials.set(n, st.note);
for (const c of dbCards) { const st = classify(c); if (st.status === "partial") partials.set(c.name, st.note); }
for (const [n, note] of [...partials].sort()) P(`- **${n}** — ${note}`);
P("");
P("### Stubs in your decks");
P("");
for (const d of deckRows) {
    const stubs = [...d.s.byName].filter(([, st]) => st.status === "stub").map(([n]) => n).sort();
    if (!stubs.length) continue;
    P(`**${d.name}** (${stubs.length}): ${stubs.join(", ")}`);
    P("");
}
const report = lines.join("\n") + "\n";

if (process.argv.includes("--write")) {
    fs.writeFileSync(path.join(__dirname, "..", "card_database", "CARD_COVERAGE_REPORT.md"), report);
    console.log("Wrote card_database/CARD_COVERAGE_REPORT.md");
}

console.log(`Database : ${db.total} cards — ${db.vanilla} vanilla, ${db.scripted} scripted, ${db.partial} partial, ${db.stub} stub (${pct(db.vanilla + db.scripted + db.partial, db.total)} implemented)`);
for (const d of deckRows) {
    const s = d.s;
    console.log(`Deck ${d.name.padEnd(30)} ${String(s.total).padStart(3)} cards — ${s.vanilla} vanilla, ${s.scripted} scripted, ${s.partial} partial, ${s.stub} stub (${pct(s.vanilla + s.scripted + s.partial, s.total)})`);
}
if (process.argv.includes("--check")) {
    // Anything registered in scripts/ must resolve to a real card somewhere (typos in names are the #1 script bug).
    const known = new Set([...dbCards.map(c => Effects.normalize(c.name))]);
    for (const d of DeckInventory.list()) { try { const dk = DeckInventory.readDeck(d.id); [...dk.mainDeck, ...dk.extraDeck].forEach(c => known.add(Effects.normalize(c.name))); } catch (e) {} }
    process.exit(0);
}
